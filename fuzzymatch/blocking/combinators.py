"""Blocking combinators: union and intersection of multiple blockers."""

from __future__ import annotations

import pandas as pd

from .base import Blocker, CandidateIndex


class UnionBlock:
    """Union of candidate sets from multiple blockers.

    Recovers recall: a true match missed by one rule may be caught by another.
    Splink's recommended default pattern for multi-pass blocking.
    """

    def __init__(self, *blockers: Blocker):
        self.blockers: list[Blocker] = list(blockers)

    def block(self, df_left: pd.DataFrame, df_right: pd.DataFrame | None = None) -> CandidateIndex:
        all_pairs: set[tuple[int, int]] = set()
        for b in self.blockers:
            ci = b.block(df_left, df_right)
            all_pairs.update(ci.pairs)
        right = df_right if df_right is not None else df_left
        return CandidateIndex(list(all_pairs), df_left.index, right.index)


class IntersectBlock:
    """Intersection of candidate sets from multiple blockers.

    Precision-focused: only candidates generated by ALL blockers are kept.
    """

    def __init__(self, *blockers: Blocker):
        self.blockers: list[Blocker] = list(blockers)

    def block(self, df_left: pd.DataFrame, df_right: pd.DataFrame | None = None) -> CandidateIndex:
        sets = [set(b.block(df_left, df_right).pairs) for b in self.blockers]
        common = set.intersection(*sets) if sets else set()
        right = df_right if df_right is not None else df_left
        return CandidateIndex(list(common), df_left.index, right.index)
