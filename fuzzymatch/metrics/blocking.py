"""Blocking quality metrics."""

from __future__ import annotations

from collections.abc import Iterable

Pair = tuple[int, int]


def block_quality_metrics(
    candidate_pairs: Iterable[Pair],
    true_pairs: Iterable[Pair],
    total_possible_pairs: int,
) -> dict[str, float]:
    """Compute Reduction Ratio, Pairs Completeness, and Pairs Quality.

    Args:
        candidate_pairs: Pairs generated by the blocker.
        true_pairs: Gold-standard matching pairs.
        total_possible_pairs: Number of pairs before blocking.

    Returns:
        Dictionary with ``reduction_ratio``, ``pairs_completeness``, and
        ``pairs_quality``.

    Raises:
        ValueError: If ``total_possible_pairs`` is not positive.
    """
    if total_possible_pairs <= 0:
        raise ValueError("total_possible_pairs must be positive")

    candidate_set = set(candidate_pairs)
    true_set = set(true_pairs)
    covered_true_pairs = candidate_set & true_set

    reduction_ratio = 1.0 - (len(candidate_set) / total_possible_pairs)
    pairs_completeness = len(covered_true_pairs) / len(true_set) if true_set else 1.0
    pairs_quality = len(covered_true_pairs) / len(candidate_set) if candidate_set else 0.0

    return {
        "reduction_ratio": max(0.0, min(1.0, reduction_ratio)),
        "pairs_completeness": pairs_completeness,
        "pairs_quality": pairs_quality,
    }
