"""Unit tests for MultiPassBlock disjunctive candidate generation and budget capping."""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from fuzzymatch.blocking import (
    BaseBlocker,
    ExactBlock,
    MultiPassBlock,
    SortedNeighborhood,
)


class TestMultiPassBlockConstruction:
    """Test constructor parameter validation and protocol compliance."""

    def test_implements_base_blocker_protocol(self) -> None:
        blocker = MultiPassBlock(
            passes=[ExactBlock(["name"])],
            budget_cap=10_000,
        )
        assert isinstance(blocker, BaseBlocker)
        assert hasattr(blocker, "block")
        assert blocker.budget_cap == 10_000
        assert len(blocker.passes) == 1

    def test_empty_passes_raises_value_error(self) -> None:
        with pytest.raises(ValueError, match="at least one blocker pass"):
            MultiPassBlock(passes=[])

    def test_invalid_budget_cap_raises_value_error(self) -> None:
        with pytest.raises(ValueError, match="positive integer"):
            MultiPassBlock(passes=[ExactBlock(["name"])], budget_cap=0)

        with pytest.raises(ValueError, match="positive integer"):
            MultiPassBlock(passes=[ExactBlock(["name"])], budget_cap=-100)


class TestMultiPassBlockExecution:
    """Test candidate accumulation, deduplication, and missing key/typo recovery."""

    def test_recovers_missing_keys_and_typos(self) -> None:
        """
        Record 0 & 1 share name='Acme' but 1 has missing tax_id.
        Record 2 & 3 share tax_id='T100' but 3 has a typo in name ('Acme' vs 'Akme').
        Single-pass on tax_id misses (0, 1). Single-pass on name misses (2, 3).
        Multi-pass on [tax_id, name] recovers both pairs.
        """
        df = pd.DataFrame(
            {
                "tax_id": ["T10", np.nan, "T100", "T100"],
                "name": ["Acme", "Acme", "Acme", "Akme"],
            },
            index=[0, 1, 2, 3],
        )

        b_tax = ExactBlock(["tax_id"])
        b_name = ExactBlock(["name"])

        # Pass 1 alone misses (0, 1)
        tax_pairs = set(b_tax.block(df).pairs)
        assert (2, 3) in tax_pairs or (3, 2) in tax_pairs
        assert (0, 1) not in tax_pairs and (1, 0) not in tax_pairs

        # Multi-pass recovers both
        mp = MultiPassBlock(passes=[b_tax, b_name], budget_cap=100)
        ci = mp.block(df)
        pairs_set = set(ci.pairs)

        assert (2, 3) in pairs_set or (3, 2) in pairs_set
        assert (0, 1) in pairs_set or (1, 0) in pairs_set

    def test_novel_candidate_accumulation_no_duplicates(self) -> None:
        """Verify that identical pairs generated by subsequent passes are not duplicated."""
        df = pd.DataFrame(
            {
                "id_col": ["A", "A", "B", "B"],
                "name": ["Corp", "Corp", "Inc", "Inc"],
            },
            index=[0, 1, 2, 3],
        )
        # Both passes will produce (0, 1) and (2, 3)
        p1 = ExactBlock(["id_col"])
        p2 = ExactBlock(["name"])

        mp = MultiPassBlock(passes=[p1, p2], budget_cap=1000)
        ci = mp.block(df)

        # In dedupe mode, ExactBlock generates bidirectional pairs (0, 1), (1, 0), (2, 3), (3, 2)
        assert len(ci.pairs) == 4
        assert len(set(ci.pairs)) == 4
        assert (0, 1) in ci.pairs
        assert (1, 0) in ci.pairs
        assert (2, 3) in ci.pairs
        assert (3, 2) in ci.pairs

    def test_budget_cap_truncation(self) -> None:
        """Verify candidate accumulation terminates strictly when budget_cap is reached."""
        df = pd.DataFrame(
            {
                "group": ["G", "G", "G", "G", "G"],  # 5 rows -> 20 directed pairs
            },
            index=list(range(5)),
        )
        blocker = ExactBlock(["group"])
        raw_pairs = blocker.block(df).pairs
        assert len(raw_pairs) == 20

        # Cap at 4
        mp = MultiPassBlock(passes=[blocker], budget_cap=4)
        ci = mp.block(df)
        assert len(ci.pairs) == 4
        assert len(ci) == 4

        # Cap at 20 (exact match)
        mp20 = MultiPassBlock(passes=[blocker], budget_cap=20)
        ci20 = mp20.block(df)
        assert len(ci20.pairs) == 20

        # Cap at 30 (budget exceeds total pairs)
        mp30 = MultiPassBlock(passes=[blocker], budget_cap=30)
        ci30 = mp30.block(df)
        assert len(ci30.pairs) == 20

    def test_budget_cap_early_pass_exit(self) -> None:
        """Verify subsequent passes are not executed when cap is exhausted by earlier pass."""
        df = pd.DataFrame(
            {
                "f1": ["A", "A", "A", "A"],  # 6 pairs
                "f2": ["B", "B", "B", "B"],
            },
            index=list(range(4)),
        )
        p1 = ExactBlock(["f1"])
        p2 = ExactBlock(["f2"])

        mp = MultiPassBlock(passes=[p1, p2], budget_cap=3)
        ci = mp.block(df)
        assert len(ci.pairs) == 3

    def test_cross_file_blocking(self) -> None:
        """Verify cross-file blocking (df_left and df_right) accumulates pairs up to cap."""
        df_left = pd.DataFrame(
            {"key": ["K1", "K2", "K3"], "name": ["Alpha", "Beta", "Gamma"]},
            index=["L1", "L2", "L3"],
        )
        df_right = pd.DataFrame(
            {"key": ["K1", "K2", "K9"], "name": ["Alpha", "BetaX", "Gamma"]},
            index=["R1", "R2", "R3"],
        )

        p1 = ExactBlock(["key"])
        p2 = ExactBlock(["name"])

        mp = MultiPassBlock(passes=[p1, p2], budget_cap=50)
        ci = mp.block(df_left, df_right)

        # p1 matches (L1, R1), (L2, R2)
        # p2 matches (L1, R1), (L3, R3)
        # Combined novel pairs: (L1, R1), (L2, R2), (L3, R3)
        assert len(ci.pairs) == 3
        assert ("L1", "R1") in ci.pairs
        assert ("L2", "R2") in ci.pairs
        assert ("L3", "R3") in ci.pairs
        assert ci.left_ids.tolist() == ["L1", "L2", "L3"]
        assert ci.right_ids.tolist() == ["R1", "R2", "R3"]

    def test_empty_dataframe_edge_cases(self) -> None:
        """Verify behavior on empty DataFrames (0 rows)."""
        df_empty = pd.DataFrame(columns=["name", "code"])
        df_non_empty = pd.DataFrame({"name": ["Test"], "code": ["C1"]})

        mp = MultiPassBlock(passes=[ExactBlock(["name"])], budget_cap=100)

        # Empty self-join
        ci_empty = mp.block(df_empty)
        assert len(ci_empty) == 0
        assert ci_empty.pairs == []

        # Empty left with non-empty right
        ci_cross_empty_left = mp.block(df_empty, df_non_empty)
        assert len(ci_cross_empty_left) == 0

        # Non-empty left with empty right
        ci_cross_empty_right = mp.block(df_non_empty, df_empty)
        assert len(ci_cross_empty_right) == 0

    def test_sorted_neighborhood_in_multi_pass(self) -> None:
        """Verify combining ExactBlock and SortedNeighborhood in multi-pass pipeline."""
        df = pd.DataFrame(
            {
                "name": ["Johnson LLC", "Johnson Corp", "Johnsonn LLC", "Smith Inc"],
            },
            index=[10, 20, 30, 40],
        )

        p1 = ExactBlock(["name"])
        p2 = SortedNeighborhood(["name"], window=2)

        mp = MultiPassBlock(passes=[p1, p2], budget_cap=500)
        ci = mp.block(df)
        assert len(ci.pairs) > 0

    def test_candidate_index_methods(self) -> None:
        """Verify CandidateIndex properties returned by MultiPassBlock."""
        df = pd.DataFrame({"id": ["X", "X"]}, index=["A", "B"])
        mp = MultiPassBlock(passes=[ExactBlock(["id"])], budget_cap=10)
        ci = mp.block(df)

        assert ("A", "B") in ci
        assert ("B", "A") in ci
        assert set(iter(ci)) == {("A", "B"), ("B", "A")}
        mi = ci.to_multiindex()
        assert isinstance(mi, pd.MultiIndex)
        assert len(mi) == 2
